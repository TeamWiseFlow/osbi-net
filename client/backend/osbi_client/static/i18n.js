  const STORAGE_KEY = "osbi.ui.language";
  let language = "en";
  try { if (window.localStorage?.getItem(STORAGE_KEY) === "zh-CN") language = "zh-CN"; } catch {}
  const bindings = new Set();
  const byNode = new WeakMap();
  const listeners = new Set();
  class LocalizedText {
    constructor(render) { this.render = render; }
    toString() { return this.render(); }
    toJSON() { return this.toString(); }
  }
  function t(key, params = {}) {
    return new LocalizedText(() => {
      const message = language === "zh-CN" ? (ZH[key] ?? key) : key;
      return message.replace(/\{(\w+)\}/g, (match, name) =>
        Object.hasOwn(params, name) ? String(params[name]) : match);
    });
  }
  function bind(node, property, value, attribute = false) {
    let current = byNode.get(node);
    if (!current) { current = new Map(); byNode.set(node, current); }
    const id = `${attribute ? "attr" : "prop"}:${property}`;
    const old = current.get(id);
    if (old) bindings.delete(old);
    const update = () => attribute ? node.setAttribute(property, String(value)) : node[property] = String(value);
    if (value instanceof LocalizedText) {
      const entry = { node, update };
      current.set(id, entry); bindings.add(entry);
    } else current.delete(id);
    update();
    return node;
  }
  function textNode(value) {
    const node = document.createTextNode("");
    return bind(node, "textContent", value);
  }
  function prune() { for (const entry of bindings) if (entry.node.isConnected === false) bindings.delete(entry); }
  function refresh() {
    if (document.documentElement) document.documentElement.lang = language;
    prune();
    for (const entry of bindings) entry.update();
    for (const listener of listeners) listener(language);
  }
  function setLanguage(value) {
    language = value === "zh-CN" ? "zh-CN" : "en";
    try { window.localStorage?.setItem(STORAGE_KEY, language); } catch {}
    refresh();
  }
  function shell() {
    for (const node of document.querySelectorAll("[data-i18n]")) bind(node, "textContent", t(node.getAttribute("data-i18n")));
    for (const attr of ["aria-label", "content"]) {
      for (const node of document.querySelectorAll(`[data-i18n-${attr}]`)) bind(node, attr, t(node.getAttribute(`data-i18n-${attr}`)), true);
    }
    refresh();
  }
  function date(value, options = {}) {
    return new LocalizedText(() => new Date(value * 1000).toLocaleString(
      language === "zh-CN" ? "zh-CN" : "en-US", { hour12: false, ...options }));
  }
