#!/usr/bin/env bash
set -euo pipefail
PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
agent=none
dsh_home="${DSH_HOME:-$HOME/.dsh}"
systemd=0
# auto: detect a running WeChat container; none: omit the override; NAME: use it.
wechat_container="${WECHAT_LINUX_CONTAINER_CONTAINER:-auto}"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --agent) [[ $# -ge 2 ]] || { printf 'Missing --agent value.\n' >&2; exit 2; }; agent="$2"; shift 2 ;;
    --dsh-home) [[ $# -ge 2 ]] || { printf 'Missing --dsh-home value.\n' >&2; exit 2; }; dsh_home="$2"; shift 2 ;;
    --systemd) systemd=1; shift ;;
    --wechat-container) [[ $# -ge 2 ]] || { printf 'Missing --wechat-container value.\n' >&2; exit 2; }; wechat_container="$2"; shift 2 ;;
    --help|-h) printf '%s\n' 'Usage: bash client/scripts/install.sh [--agent none|dsh] [--dsh-home PATH] [--systemd] [--wechat-container NAME|auto|none]' 'Installs backend, browser and assets; reuses or provisions Python/Node.' 'The optional dsh step installs OSBI skills, not the DSH host.' 'The optional systemd step installs and starts a systemd --user unit that keeps the backend resident.' 'The optional wechat container sets WECHAT_LINUX_CONTAINER_CONTAINER for MP source capture; auto detects a running wechat-linux-container or mimicwx container.'; exit 0 ;;
    *) printf 'Unknown option: %s\n' "$1" >&2; exit 2 ;;
  esac
done
[[ "$agent" == none || "$agent" == dsh ]] || { printf 'Only the dsh adapter is currently available.\n' >&2; exit 2; }
source "$PROJECT_ROOT/client/scripts/runtime.sh"
platform="$(osbi_platform)"
mkdir -p "$PROJECT_ROOT/.osbi/runtime" "$PROJECT_ROOT/.osbi/bin"
mkdir "$PROJECT_ROOT/.osbi/install.lock" 2>/dev/null || { printf 'Client installation is already running; inspect .osbi/install.lock if interrupted.\n' >&2; exit 1; }
trap 'rmdir "$PROJECT_ROOT/.osbi/install.lock"' EXIT
osbi_prepare_node "$PROJECT_ROOT" "$platform"
osbi_prepare_python "$PROJECT_ROOT" "$platform"
if [[ ! -e "$PROJECT_ROOT/.venv" ]]; then "$OSBI_INSTALL_PYTHON" -m venv "$PROJECT_ROOT/.venv"; fi
"$PROJECT_ROOT/.venv/bin/python" -m pip install -c "$PROJECT_ROOT/requirements.lock" -e "${PROJECT_ROOT}[client]"
npm ci --ignore-scripts --prefix "$PROJECT_ROOT/client/backend/browser"
npm run build --prefix "$PROJECT_ROOT/client/backend/browser"
node "$PROJECT_ROOT/client/backend/browser/scripts/install-assets.mjs"
if [[ "$agent" == dsh ]]; then "$PROJECT_ROOT/.venv/bin/python" "$PROJECT_ROOT/client/scripts/deepseek-harness/install.py" --home "$dsh_home"; fi
if [[ "$systemd" == 1 ]]; then
  command -v systemctl >/dev/null 2>&1 || { printf 'systemctl is not available; skipping --systemd.\n' >&2; exit 1; }
  # Recent clients default to the container name wechat-linux-container, while
  # existing deployments often keep the older mimicwx-linux name. Resolve it
  # once so MP capture keeps working after an upgrade.
  container=''
  case "$wechat_container" in
    none|'') ;;
    auto)
      if command -v docker >/dev/null 2>&1; then
        names="$(docker ps --format '{{.Names}}' 2>/dev/null || true)"
        container="$(printf '%s\n' "$names" | grep -x 'wechat-linux-container' | head -n 1 || true)"
        if [[ -z "$container" ]]; then
          container="$(printf '%s\n' "$names" | grep -E '^mimicwx' | head -n 1 || true)"
        fi
      fi ;;
    *) container="$wechat_container" ;;
  esac
  unit_dir="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
  unit="$unit_dir/osbi-client.service"
  mkdir -p "$unit_dir"
  if [[ -e "$unit" ]]; then cp -a "$unit" "$unit.bak-$(date +%F-%H%M)"; fi
  {
    printf '%s\n' \
      '# Generated by client/scripts/install.sh --systemd.' \
      '[Unit]' \
      'Description=OSBI local client backend' \
      'After=network-online.target' \
      'Wants=network-online.target' \
      '' \
      '[Service]' \
      'Type=simple'
    printf 'WorkingDirectory=%s\n' "$PROJECT_ROOT"
    if [[ -n "$container" ]]; then
      printf 'Environment=WECHAT_LINUX_CONTAINER_CONTAINER=%s\n' "$container"
    fi
    printf 'ExecStart=/bin/bash "%s/client/scripts/run.sh" serve\n' "$PROJECT_ROOT"
    printf '%s\n' \
      'Restart=on-failure' \
      'RestartSec=5' \
      'TimeoutStopSec=60' \
      'UMask=0077' \
      '' \
      '[Install]' \
      'WantedBy=default.target'
  } > "$unit"
  systemctl --user daemon-reload
  systemctl --user enable --now osbi-client.service
  if [[ -n "$container" ]]; then
    printf 'Resident backend unit installed and started: %s (MP container: %s)\n' "$unit" "$container"
  else
    printf 'Resident backend unit installed and started: %s\n' "$unit"
    if [[ "$wechat_container" == auto ]]; then
      printf 'No WeChat container detected; pass --wechat-container NAME if MP sources capture from one.\n'
    fi
  fi
fi
printf 'Client and browser installed. Start: bash "%s/client/scripts/run.sh"\n' "$PROJECT_ROOT"
